#!/usr/bin/env python3
"""Build trusted PGN Mentor opening-archive metadata for the public proxy."""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import time
import urllib.parse
import urllib.request
import zipfile
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG_PATH = ROOT / "data/pgn/pgnmentor-remote-catalog.json"
OUTPUT_PATH = ROOT / "api/pgn/pgnmentor-opening-metadata.js"
SOURCE_BASE_URL = "https://www.pgnmentor.com/openings/"
USER_AGENT = "CAISSA-Chess-PGN-Metadata/1.0 (+https://www.caissa-chess.org/)"
PAGE_SIZE = 100
MAX_ZIP_BYTES = 32 * 1024 * 1024
MAX_PGN_BYTES = 96 * 1024 * 1024


def fetch_archive(filename: str) -> tuple[bytes, dict[str, str]]:
    url = SOURCE_BASE_URL + urllib.parse.quote(filename, safe="")
    last_error: Exception | None = None
    for attempt in range(3):
        try:
            request = urllib.request.Request(
                url,
                headers={"User-Agent": USER_AGENT, "Accept": "application/zip, application/octet-stream"},
            )
            with urllib.request.urlopen(request, timeout=90) as response:
                declared = int(response.headers.get("Content-Length") or 0)
                if declared > MAX_ZIP_BYTES:
                    raise RuntimeError(f"{filename}: declared ZIP size exceeds limit")
                data = response.read(MAX_ZIP_BYTES + 1)
                headers = {
                    "etag": response.headers.get("ETag") or "",
                    "lastModified": response.headers.get("Last-Modified") or "",
                }
            if len(data) > MAX_ZIP_BYTES:
                raise RuntimeError(f"{filename}: ZIP size exceeds limit")
            return data, headers
        except Exception as error:  # noqa: BLE001 - retry and report the final source error
            last_error = error
            if attempt < 2:
                time.sleep(1.5 * (attempt + 1))
    raise RuntimeError(f"{filename}: download failed after retries: {last_error}")


def count_games(pgn_bytes: bytes) -> int:
    text = pgn_bytes.decode("utf-8", errors="replace").lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")
    chunks = re.split(r'(?=^\[Event\s+")', text, flags=re.MULTILINE)
    return sum(
        1
        for chunk in chunks
        if (game := chunk.strip()).startswith("[Event ") and "[White " in game and "[Black " in game
    )


def inspect_archive(filename: str) -> tuple[str, dict[str, object]]:
    zip_bytes, source_headers = fetch_archive(filename)
    try:
        with zipfile.ZipFile(io.BytesIO(zip_bytes)) as archive:
            entries = [item for item in archive.infolist() if not item.is_dir() and item.filename.lower().endswith(".pgn")]
            if len(entries) != 1:
                raise RuntimeError(f"expected one PGN entry, found {len(entries)}")
            entry = entries[0]
            if entry.file_size > MAX_PGN_BYTES:
                raise RuntimeError("PGN size exceeds limit")
            pgn_bytes = archive.read(entry)
    except zipfile.BadZipFile as error:
        raise RuntimeError(f"{filename}: invalid ZIP: {error}") from error
    if len(pgn_bytes) > MAX_PGN_BYTES:
        raise RuntimeError(f"{filename}: expanded PGN exceeds limit")
    game_count = count_games(pgn_bytes)
    if game_count < 1:
        raise RuntimeError(f"{filename}: no valid PGN games")
    return filename, {
        "games": game_count,
        "pages": (game_count + PAGE_SIZE - 1) // PAGE_SIZE,
        "zipBytes": len(zip_bytes),
        "pgnBytes": len(pgn_bytes),
        "zipSha256": hashlib.sha256(zip_bytes).hexdigest(),
        **source_headers,
    }


def render(metadata: dict[str, dict[str, object]], generated_at: str, source_updated: str | None) -> str:
    lines = [
        "// Generated by scripts/update-pgnmentor-opening-metadata.py. Do not hand-edit.",
        f"// Source: {SOURCE_BASE_URL}",
        f"// Generated: {generated_at}",
        f"// Source updated: {source_updated or 'unknown'}",
        "export const PGN_MENTOR_OPENING_METADATA = Object.freeze({",
    ]
    for filename in sorted(metadata, key=str.casefold):
        value = json.dumps(metadata[filename], ensure_ascii=False, separators=(",", ":"))
        lines.append(f"    {json.dumps(filename)}: Object.freeze({value}),")
    lines.extend(["});", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()
    if args.workers < 1 or args.workers > 8:
        raise SystemExit("--workers must be between 1 and 8")

    catalog = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    openings = catalog.get("openings")
    if not isinstance(openings, list) or len(openings) != catalog.get("openingCount") or len(openings) < 100:
        raise RuntimeError("PGN Mentor opening catalog is missing or inconsistent")

    metadata: dict[str, dict[str, object]] = {}
    with ThreadPoolExecutor(max_workers=args.workers) as executor:
        futures = {executor.submit(inspect_archive, filename): filename for filename in openings}
        for completed, future in enumerate(as_completed(futures), start=1):
            filename, record = future.result()
            metadata[filename] = record
            print(f"[{completed}/{len(openings)}] {filename}: {record['games']} games, {record['pages']} pages")

    if set(metadata) != set(openings):
        raise RuntimeError("generated metadata does not match the opening allowlist")
    generated_at = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    rendered = render(metadata, generated_at, catalog.get("sourceUpdates", {}).get("openings"))
    OUTPUT_PATH.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Wrote {len(metadata)} trusted opening records to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
