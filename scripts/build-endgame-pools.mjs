import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ChessRulesFacade } from '../js/endgame-trainer/chess-rules-facade.js';
import {
    CURATED_POOL_CONTRACT_VERSION,
    computeCompatibilityFingerprint,
    stableStringify,
    validateAuthoredPoolSource,
    validatePublishedPoolArtifact
} from '../js/endgame-trainer/v2/curated-pool-validator.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const AUTHORING_DIRECTORY = join(ROOT, 'endgame-pools', 'authoring', 'pools');
const OUTPUT_DIRECTORY = join(ROOT, 'public', 'data', 'endgame-pools');
const REGISTRY_PATH = join(ROOT, 'js', 'endgame-trainer', 'v2', 'curated-pool-registry.js');

function normalizedMove(fen, response) {
    const rules = ChessRulesFacade.fromFen(fen);
    const move = rules.move(response);
    return Object.freeze({ lan: `${move.from}${move.to}${move.promotion || ''}`, san: move.san });
}

function publishedPosition(position) {
    const expected = normalizedMove(position.fen, position.expectedMove);
    const acceptedAlternatives = position.acceptedAlternatives.map((move) => normalizedMove(position.fen, move));
    return {
        schemaVersion: position.schemaVersion,
        positionId: position.positionId,
        title: position.title,
        theme: position.theme,
        fen: ChessRulesFacade.fromFen(position.fen).fen(),
        sideToMove: position.sideToMove,
        objective: position.objective,
        expectedMove: expected.san,
        expectedLan: expected.lan,
        expectedSan: expected.san,
        acceptedAlternatives,
        hintStages: position.hintStages,
        feedback: position.feedback,
        difficulty: position.difficulty,
        verification: position.verification,
        eligibility: position.eligibility,
        provenance: position.provenance,
        conceptMappings: position.conceptMappings
    };
}

export function buildPublishedPool(source) {
    validateAuthoredPoolSource(source, { throwOnError: true });
    const positions = source.positions.map(publishedPosition);
    const artifact = {
        schemaVersion: source.schemaVersion,
        contractVersion: CURATED_POOL_CONTRACT_VERSION,
        poolId: source.poolId,
        poolVersion: source.poolVersion,
        label: source.label,
        description: source.description,
        theme: source.theme,
        difficultyBand: source.difficultyBand,
        objectiveTypes: [...new Set(positions.map(({ objective }) => objective.type))].sort(),
        positionIds: positions.map(({ positionId }) => positionId),
        positionCount: positions.length,
        verificationSummary: {
            legalityVerified: positions.every(({ verification }) => verification.legalFen && verification.legalExpectedMove),
            rulesVerified: positions.every(({ verification }) => verification.objectiveCompatible),
            engineReviewedCount: positions.filter(({ verification }) => verification.engineReviewed).length,
            tablebaseVerifiedCount: positions.filter(({ verification }) => verification.tablebaseVerified).length,
            editoriallyApprovedCount: positions.filter(({ verification }) => verification.editorialApproved).length
        },
        scoringEligibility: 'preview-score-only',
        personalBestEligibility: false,
        futureLeaderboardEligibility: false,
        repeatPolicy: source.repeatPolicy,
        selectionPolicy: source.selectionPolicy,
        provenanceSummary: {
            sourceType: 'immutable-knowledge-activities',
            releaseIds: [...new Set(positions.map(({ provenance }) => provenance.releaseId))].sort()
        },
        positions
    };
    return {
        ...artifact,
        contentFingerprint: computeCompatibilityFingerprint(artifact)
    };
}

function artifactBytes(artifact) {
    return `${stableStringify(artifact)}\n`;
}

function registryBytes(entries) {
    return `// Generated by scripts/build-endgame-pools.mjs. Do not edit by hand.\n` +
        `export const CURATED_POOL_REGISTRY = Object.freeze(${JSON.stringify(entries, null, 4)}.map((entry) => Object.freeze(entry)));\n`;
}

async function loadSources() {
    const files = (await readdir(AUTHORING_DIRECTORY)).filter((file) => file.endsWith('.json')).sort();
    return Promise.all(files.map(async (file) => ({
        file,
        source: JSON.parse(await readFile(join(AUTHORING_DIRECTORY, file), 'utf8'))
    })));
}

export async function buildAllPools({ check = false } = {}) {
    const sources = await loadSources();
    if (!sources.length) throw new Error('no-authored-endgame-pools');
    const outputs = [];
    const registry = [];
    for (const { source } of sources) {
        const artifact = buildPublishedPool(source);
        validatePublishedPoolArtifact(artifact, {
            poolId: source.poolId,
            poolVersion: source.poolVersion,
            contentFingerprint: artifact.contentFingerprint
        }, { throwOnError: true });
        const outputPath = join(OUTPUT_DIRECTORY, source.poolId, `${source.poolVersion}.json`);
        const bytes = artifactBytes(artifact);
        outputs.push({ outputPath, bytes, artifact });
        registry.push({
            poolId: artifact.poolId,
            poolVersion: artifact.poolVersion,
            contentFingerprint: artifact.contentFingerprint,
            positionCount: artifact.positionCount,
            url: `/data/endgame-pools/${artifact.poolId}/${artifact.poolVersion}.json`
        });
    }
    const registryContent = registryBytes(registry);
    if (check) {
        for (const { outputPath, bytes } of outputs) {
            const existing = await readFile(outputPath, 'utf8').catch(() => null);
            if (existing !== bytes) throw new Error(`stale-endgame-pool:${relative(ROOT, outputPath)}`);
        }
        const existingRegistry = await readFile(REGISTRY_PATH, 'utf8').catch(() => null);
        if (existingRegistry !== registryContent) throw new Error('stale-endgame-pool-registry');
    } else {
        for (const { outputPath, bytes } of outputs) {
            await mkdir(dirname(outputPath), { recursive: true });
            await writeFile(outputPath, bytes, 'utf8');
        }
        await writeFile(REGISTRY_PATH, registryContent, 'utf8');
    }
    return Object.freeze({
        poolCount: outputs.length,
        positionCount: outputs.reduce((sum, output) => sum + output.artifact.positionCount, 0),
        fingerprints: Object.freeze(registry.map(({ contentFingerprint }) => contentFingerprint))
    });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const check = process.argv.includes('--check');
    const result = await buildAllPools({ check });
    console.log(`${check ? 'Validated' : 'Built'} ${result.poolCount} curated endgame pool(s), ${result.positionCount} positions.`);
}
