import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';
import {
  readCanonicalText,
  serializeCanonicalText,
  writeCanonicalText
} from './lib/canonical-text.mjs';

const root = new URL('../', import.meta.url);
const navigationSource = await readFile(new URL('js/caissa-primary-navigation.js', root), 'utf8');
const documentStub = { querySelectorAll: () => [] };
const sandbox = { window: {}, document: documentStub };
vm.runInNewContext(navigationSource, sandbox, { filename: 'caissa-primary-navigation.js' });
const navigation = sandbox.window.CaissaPrimaryNavigation;
const checkOnly = process.argv.includes('--check');

function replaceElementContents(html, attribute, content) {
  const openPattern = new RegExp(`<([a-z][\\w-]*)\\b[^>]*\\b${attribute}(?:=["'][^"']*["'])?[^>]*>`, 'i');
  const match = openPattern.exec(html);
  if (!match) throw new Error(`NAVIGATION_FALLBACK_HOST_MISSING: ${attribute}`);
  const tag = match[1];
  const tokenPattern = new RegExp(`<\\/?${tag}\\b[^>]*>`, 'gi');
  tokenPattern.lastIndex = match.index + match[0].length;
  let depth = 1;
  let token;
  while ((token = tokenPattern.exec(html))) {
    depth += token[0][1] === '/' ? -1 : 1;
    if (depth === 0) {
      const start = match.index + match[0].length;
      return `${html.slice(0, start)}${content}${html.slice(token.index)}`;
    }
  }
  throw new Error(`NAVIGATION_FALLBACK_HOST_UNCLOSED: ${attribute}`);
}

async function build(file, adapterName, activeKey) {
  const url = new URL(file, root);
  const original = await readFile(url, 'utf8');
  const adapter = navigation.adapters[adapterName];
  const options = { activeKey };
  let generated = replaceElementContents(
    original,
    'data-caissa-primary-groups',
    adapter.renderBody(options)
  );
  generated = replaceElementContents(
    generated,
    'data-caissa-social-footer',
    adapter.renderSocialFooter()
  );
  if (checkOnly && generated !== original) throw new Error(`NAVIGATION_FALLBACK_OUTDATED: ${file}`);
  if (!checkOnly) await writeFile(url, generated);
}

async function buildPlayDocumentModule() {
  const moduleUrl = new URL('api/_lib/play-v2-public-beta-document.js', root);
  const [publicBetaHtml, unavailableHtml, original] = await Promise.all([
    readCanonicalText(new URL('play-v2-public-beta.html', root)),
    readCanonicalText(new URL('play-v2-unavailable.html', root)),
    readCanonicalText(moduleUrl)
  ]);
  const generated = `// Generated by scripts/build-play-v2.mjs and scripts/build-navigation-fallbacks.mjs. Do not edit directly.\n`
    + `export const PLAY_V2_PUBLIC_BETA_DOCUMENT = ${serializeCanonicalText(publicBetaHtml)};\n`
    + `export const PLAY_V2_UNAVAILABLE_DOCUMENT = ${serializeCanonicalText(unavailableHtml)};\n`;
  if (checkOnly && generated !== original) throw new Error('NAVIGATION_FALLBACK_OUTDATED: api/_lib/play-v2-public-beta-document.js');
  if (!checkOnly) await writeCanonicalText(moduleUrl, generated);
}

